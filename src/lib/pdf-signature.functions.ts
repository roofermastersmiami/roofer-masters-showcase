// tenant-audit: reviewed — PDF Studio signature requests are company-scoped.
// Staff endpoints derive the caller's company from crm_company_memberships
// (never from client input) and check the membership role before any
// service-role access; every service-role read/write is filtered by that
// company id. Public endpoints hold no session: they authorize solely by a
// per-signer capability token (uuid, stored only inside the request's
// signers jsonb), expose only that signer's fields, and can only complete
// that signer's fields once, before expiry, unless revoked.

const BUCKET = "pdf-signature-documents";
const STAFF_ROLES = ["owner", "admin", "office", "sales"];

type SignatureRequestRow = {
  id: string;
  company_id: string;
  document_name: string;
  document_path: string;
  signed_path: string | null;
  signers: SignatureSigner[];
  fields: SignatureField[];
  field_values: Record<string, string>;
  status: "pending" | "completed";
  expires_at: string;
  revoked_at: string | null;
  completed_at: string | null;
  created_at: string;
};

// Migration 0055 ships pdf_signature_requests; the generated Supabase types
// are regenerated by Lovable, so table access goes through this shim until
// the table appears in src/integrations/supabase/types.ts.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
function requestsTable(admin: any) {
  return admin.from("pdf_signature_requests") as {
    insert: (row: Record<string, unknown>) => {
      select: (cols: string) => { single: () => Promise<{ data: unknown; error: unknown }> };
    };
    select: (cols: string) => // eslint-disable-next-line @typescript-eslint/no-explicit-any
    any;
    update: (
      row: Record<string, unknown>,
    ) => // eslint-disable-next-line @typescript-eslint/no-explicit-any
    any;
  };
}

async function staffContext(context: {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  supabase: { from: (table: string) => any };
  userId: string;
}): Promise<{ companyId: string }> {
  const { data, error } = await context.supabase
    .from("crm_company_memberships")
    .select("company_id,role")
    .eq("user_id", context.userId)
    .maybeSingle();
  const membership = data as { company_id: string; role: string } | null;
  if (error || !membership) throw new Error("A single company membership is required");
  if (!STAFF_ROLES.includes(membership.role))
    throw new Error("You do not have access to this action");
  return { companyId: membership.company_id };
}

function base64ToBytes(base64: string): Uint8Array {
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

async function findRequestByToken(
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  admin: any,
  token: string,
): Promise<{ request: SignatureRequestRow; signerIndex: number } | null> {
  const { data, error } = await requestsTable(admin)
    .select("*")
    .contains("signers", [{ token }])
    .maybeSingle();
  if (error) throw new Error("Could not verify signing link");
  const request = data as SignatureRequestRow | null;
  if (!request) return null;
  const signerIndex = request.signers.findIndex((signer) => signer.token === token);
  if (signerIndex < 0) return null;
  return { request, signerIndex };
}

export const createSignatureRequest = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: unknown) => createSignatureRequestSchema.parse(input))
  .handler(async ({ data, context }) => {
    setResponseHeader("Cache-Control", "private, no-store");
    const { companyId } = await staffContext(context);
    const bytes = base64ToBytes(data.documentBase64);
    if (!validPdfHeader(bytes)) throw new Error("That file is not a PDF.");
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
    const requestId = crypto.randomUUID();
    const documentPath = `${companyId}/${requestId}/original.pdf`;
    const { error: uploadError } = await supabaseAdmin.storage
      .from(BUCKET)
      .upload(documentPath, bytes, { contentType: "application/pdf", upsert: false });
    if (uploadError) throw new Error("Could not store the document");
    const signers: SignatureSigner[] = data.signers.map((signer) => ({
      name: signer.name,
      email: signer.email,
      token: crypto.randomUUID(),
      completedAt: null,
    }));
    const fields: SignatureField[] = data.fields.map((field) => ({
      ...field,
      signerIndex: Math.min(field.signerIndex, signers.length - 1),
    }));
    const { data: row, error } = await requestsTable(supabaseAdmin)
      .insert({
        id: requestId,
        company_id: companyId,
        created_by: context.userId,
        document_name: data.documentName,
        document_path: documentPath,
        signers,
        fields,
      })
      .select("id, expires_at")
      .single();
    if (error || !row) throw new Error("Could not create the signature request");
    const created = row as { id: string; expires_at: string };
    return {
      id: created.id,
      expiresAt: created.expires_at,
      signers: signers.map((signer) => ({
        name: signer.name,
        email: signer.email,
        token: signer.token,
      })),
    };
  });

export const listSignatureRequests = createServerFn({ method: "GET" })
  .middleware([requireSupabaseAuth])
  .handler(async ({ context }) => {
    const { companyId } = await staffContext(context);
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
    const { data, error } = await requestsTable(supabaseAdmin)
      .select(
        "id, document_name, signers, fields, status, signed_path, expires_at, revoked_at, completed_at, created_at",
      )
      .eq("company_id", companyId)
      .order("created_at", { ascending: false })
      .limit(50);
    if (error) throw new Error("Could not load signature requests");
    const rows = (data ?? []) as Array<
      Pick<
        SignatureRequestRow,
        | "id"
        | "document_name"
        | "signers"
        | "fields"
        | "status"
        | "signed_path"
        | "expires_at"
        | "revoked_at"
        | "completed_at"
        | "created_at"
      >
    >;
    return rows.map((row) => ({
      id: row.id,
      documentName: row.document_name,
      status: row.status,
      hasSignedCopy: Boolean(row.signed_path),
      fieldCount: row.fields.length,
      signers: row.signers.map((signer) => ({
        name: signer.name,
        email: signer.email,
        token: signer.token,
        completedAt: signer.completedAt,
      })),
      expiresAt: row.expires_at,
      revokedAt: row.revoked_at,
      completedAt: row.completed_at,
      createdAt: row.created_at,
    }));
  });

export const getSignatureRequestDownload = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: unknown) =>
    z
      .object({
        requestId: z.string().uuid(),
        kind: z.enum(["original", "signed"]),
      })
      .parse(input),
  )
  .handler(async ({ data, context }) => {
    const { companyId } = await staffContext(context);
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
    const { data: row, error } = await requestsTable(supabaseAdmin)
      .select("document_path, signed_path")
      .eq("id", data.requestId)
      .eq("company_id", companyId)
      .maybeSingle();
    if (error || !row) throw new Error("Signature request not found");
    const found = row as Pick<SignatureRequestRow, "document_path" | "signed_path">;
    const path = data.kind === "signed" ? found.signed_path : found.document_path;
    if (!path) throw new Error("That document is not available yet");
    const { data: signed, error: signedError } = await supabaseAdmin.storage
      .from(BUCKET)
      .createSignedUrl(path, 300);
    if (signedError || !signed?.signedUrl) throw new Error("Could not prepare the download");
    return { url: signed.signedUrl };
  });

export const revokeSignatureRequest = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((input: unknown) => z.object({ requestId: z.string().uuid() }).parse(input))
  .handler(async ({ data, context }) => {
    const { companyId } = await staffContext(context);
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
    const { data: revoked, error } = await requestsTable(supabaseAdmin)
      .update({ revoked_at: new Date().toISOString() })
      .eq("id", data.requestId)
      .eq("company_id", companyId)
      .is("revoked_at", null)
      .select("id")
      .maybeSingle();
    if (error || !revoked) throw new Error("Could not revoke that link");
    return { ok: true };
  });

// Public capability endpoint: the per-signer token is the authorization.
// Returns only that signer's fields plus a short-lived URL for the current
// document (original, or the copy already stamped by an earlier signer).
export const getPublicSignatureRequest = createServerFn({ method: "GET" })
  .inputValidator((input: unknown) => signerTokenParamSchema.parse(input))
  .handler(async ({ data }) => {
    setResponseHeader("Cache-Control", "private, no-store");
    setResponseHeader("Referrer-Policy", "no-referrer");
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
    const found = await findRequestByToken(supabaseAdmin, data.token);
    if (!found) return null;
    const { request, signerIndex } = found;
    if (request.revoked_at || new Date(request.expires_at).getTime() <= Date.now()) return null;
    const signer = request.signers[signerIndex]!;
    const path = request.signed_path ?? request.document_path;
    const { data: signed, error: signedError } = await supabaseAdmin.storage
      .from(BUCKET)
      .createSignedUrl(path, 900);
    if (signedError || !signed?.signedUrl) throw new Error("Could not prepare the document");
    return {
      documentName: request.document_name,
      documentUrl: signed.signedUrl,
      signerName: signer.name,
      signerEmail: signer.email,
      signerIndex,
      fields: request.fields.filter((field) => field.signerIndex === signerIndex),
      signerCompletedAt: signer.completedAt,
      requestCompleted: request.status === "completed",
      otherSignerPending: request.signers.some(
        (other, index) => index !== signerIndex && !other.completedAt,
      ),
      expiresAt: request.expires_at,
    };
  });

// Public capability endpoint: the same token authorizes this signer to
// complete their fields exactly once. Values are validated server-side,
// stamped onto the document with pdf-lib, and the stamped copy becomes
// the working document for any remaining signer.
export const completeSignatureRequest = createServerFn({ method: "POST" })
  .inputValidator((input: unknown) => completeSignatureRequestSchema.parse(input))
  .handler(async ({ data }) => {
    setResponseHeader("Cache-Control", "private, no-store");
    setResponseHeader("Referrer-Policy", "no-referrer");
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
    const found = await findRequestByToken(supabaseAdmin, data.token);
    if (!found) throw new Error("This signing link is no longer available");
    const { request, signerIndex } = found;
    const signer = request.signers[signerIndex]!;
    if (!signerLinkIsActive(request, signer))
      throw new Error(
        signer.completedAt
          ? "You have already signed this document"
          : "This signing link is no longer available",
      );
    const missing = missingRequiredValues(request.fields, signerIndex, data.values);
    if (missing.length) throw new Error(`Please complete: ${missing.join(", ")}`);
    const invalid = validateSignerValues(request.fields, signerIndex, data.values);
    if (invalid) throw new Error(invalid);
    const workingPath = request.signed_path ?? request.document_path;
    const { data: file, error: downloadError } = await supabaseAdmin.storage
      .from(BUCKET)
      .download(workingPath);
    if (downloadError || !file) throw new Error("Could not load the document to sign");
    const original = new Uint8Array(await file.arrayBuffer());
    const stamped = await stampSignerFields(original, request.fields, signerIndex, data.values);
    const signedPath = `${request.company_id}/${request.id}/signed.pdf`;
    const { error: uploadError } = await supabaseAdmin.storage
      .from(BUCKET)
      .upload(signedPath, stamped, { contentType: "application/pdf", upsert: true });
    if (uploadError) throw new Error("Could not save the signed document");
    const completedAt = new Date().toISOString();
    const signers = request.signers.map((entry, index) =>
      index === signerIndex ? { ...entry, completedAt } : entry,
    );
    const finished = allSignersCompleted(signers);
    const { data: updated, error: updateError } = await requestsTable(supabaseAdmin)
      .update({
        signers,
        field_values: { ...request.field_values, ...data.values },
        signed_path: signedPath,
        status: finished ? "completed" : "pending",
        completed_at: finished ? completedAt : null,
      })
      .eq("id", request.id)
      .is("revoked_at", null)
      .select("id")
      .maybeSingle();
    if (updateError || !updated) throw new Error("Could not record your signature");
    return { completedAt, requestCompleted: finished };
  });
