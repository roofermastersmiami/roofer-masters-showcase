-- Company-scoped in-app notifications for the permitting automation layer.
-- Rows are created by authenticated server functions when a permit status
-- changes, an inspection is scheduled or resulted, or an issued permit
-- approaches/passes its expiration date. Expiration notifications are
-- deduplicated per permit and threshold through the partial unique index on
-- (company_id, dedupe_key); event notifications carry no dedupe key.
-- tenant-audit: reviewed — company_id is derived server-side from the
-- caller's single company membership (permitContext), never from browser
-- input; RLS restricts every operation to company owners/admins, matching
-- the permitting module's existing role boundary, and the composite foreign
-- key keeps a notification's permit application inside the same company.

CREATE TABLE public.crm_notifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES public.crm_companies(id) ON DELETE RESTRICT,
  kind text NOT NULL
    CHECK (kind IN (
      'permit_status_changed',
      'inspection_scheduled',
      'inspection_result',
      'permit_expiring_soon',
      'permit_expired'
    )),
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
  body text NOT NULL DEFAULT '' CHECK (char_length(body) <= 2000),
  permit_application_id uuid,
  dedupe_key text CHECK (dedupe_key IS NULL OR char_length(dedupe_key) <= 200),
  read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT crm_notifications_application_company_fkey
    FOREIGN KEY (permit_application_id, company_id)
    REFERENCES public.roof_permit_applications(id, company_id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX crm_notifications_dedupe_key
  ON public.crm_notifications(company_id, dedupe_key)
  WHERE dedupe_key IS NOT NULL;

CREATE INDEX crm_notifications_company_created_idx
  ON public.crm_notifications(company_id, created_at DESC);

ALTER TABLE public.crm_notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.crm_notifications FORCE ROW LEVEL SECURITY;
REVOKE ALL ON public.crm_notifications FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.crm_notifications TO authenticated;
GRANT ALL ON public.crm_notifications TO service_role;

CREATE POLICY "Company admins read notifications"
  ON public.crm_notifications FOR SELECT TO authenticated
  USING (public.is_crm_company_admin(company_id));
CREATE POLICY "Company admins create notifications"
  ON public.crm_notifications FOR INSERT TO authenticated
  WITH CHECK (public.is_crm_company_admin(company_id));
CREATE POLICY "Company admins update notifications"
  ON public.crm_notifications FOR UPDATE TO authenticated
  USING (public.is_crm_company_admin(company_id))
  WITH CHECK (public.is_crm_company_admin(company_id));
CREATE POLICY "Company admins delete notifications"
  ON public.crm_notifications FOR DELETE TO authenticated
  USING (public.is_crm_company_admin(company_id));

COMMENT ON TABLE public.crm_notifications IS
  'Company-owned in-app notifications generated by permitting automation (status changes, inspection scheduling/results, expiration thresholds). Event rows are informational; expiration rows are deduplicated per permit and threshold.';
